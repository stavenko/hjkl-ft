//! Пересчитать все блюда из состава — и стереть то, что за них выдумала модель.
//!
//! Питательность блюда — функция от состава: `finish_recipe` складывал калории и
//! нутриенты ингредиентов и делил на итоговый вес, то есть уварка учитывалась.
//! А ЖЕЛЕЗО у блюда не считалось вовсе: поле оставалось пустым, фоновый проход
//! видел «не хватает» и спрашивал модель — по НАЗВАНИЮ блюда.
//!
//! Отсюда наблюдавшееся: у готового блюда с мидиями оказывались ровно мидийные
//! 4,5 мг при усвоении 25 %. Модель узнавала в названии продукт и отдавала его
//! строку целиком, не зная ни доли мидий в массе, ни уварки. Завышены при этом
//! обе величины сразу, и в подсчёте усвоенного они перемножаются.
//!
//! Заодно правится второе: `change_recipe_weight` пересчитывал под новый вес
//! калории и нутриенты, но не железо — оно ведь было не его. Значит у блюд, чей
//! вес правили, железо не соответствовало даже собственному названию.
//!
//! Пересчёт идёт от внутренних рецептов к внешним: блюдо может быть ингредиентом
//! другого блюда, и внешнее, посчитанное раньше внутреннего, унаследовало бы
//! старые числа.
//!
//! Записывается только изменившееся, поэтому у того, кто рецептов не заводил,
//! миграция не порождает ни одной записи.

use crate::services::local;

pub const VERSION: u32 = 5;
pub const DESCRIPTION: &str = "пересчитать блюда из состава, стерев угаданное моделью";

pub async fn script() -> Result<(), String> {
    let changed = local::recompute_all_recipes().await;
    leptos::logging::log!("миграция 5: пересчитано блюд — {changed}");
    Ok(())
}
