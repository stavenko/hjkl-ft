//! Вес порции по снимку: площадь и объём считаются здесь, а не моделью.
//!
//! Прямой вопрос «сколько тут граммов» все восемь доступных моделей отвечают на
//! 50-73% ниже правды, и это не чинится ни промптом, ни размером модели — замер и
//! таблица по моделям лежат в `scripts/measure-per-image.mjs`. Причина видна в их
//! же ответах: одна и та же модель описывала мясо как «половина тарелки, слой 2-3
//! см» — около 700 см³ — и тут же называла 150 г. Геометрию она описывает щедро,
//! число называет скупо; значит число берётся не из описания.
//!
//! Поэтому у модели спрашивают только то, что она умеет, и спрашивают ПОРОЗНЬ:
//! отдельным запросом размер посуды, отдельным — что на ней лежит и сколько места
//! занимает. Граммы не спрашивают вовсе, их считает этот модуль.
//!
//! ЧЕГО ЭТОТ СПОСОБ НЕ УМЕЕТ, и это надо знать всякому, кто им пользуется. На горке
//! он хорош, на плоском промахивается вдвое:
//!
//!   печень 300 г + капуста 400 г (горки)    -8% и -4%
//!   скумбрия 83 г + сельдь 72 г (плоское)   +70…+127%
//!
//! Поперечник посуды при этом мерился точно (19.2 см при 19), значит промах целиком
//! в толщине слоя. Толщины на снимке СВЕРХУ просто нет: поперечник лежит в плоскости
//! кадра и потому измерим, а высота перпендикулярна ей, и сведений о ней в одном
//! виде сверху не содержится. Модель её не измеряет, а вспоминает типичную для
//! такого блюда — на капусте с мясом типичная совпала, на рыбе нет.
//!
//! Отсюда правило для интерфейса: оценка по снимку и названный человеком вес — не
//! одно и то же по надёжности, и различать их должен человек, а не мы за него.

/// Насколько плотно уложена еда в том объёме, который она занимает.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Packing {
    /// Сплошной кусок без пустот: филе, котлета, ломоть, ломтик сыра.
    Solid,
    /// Вязкая масса, пустот почти нет: каша, пюре, тушёное с подливой.
    Packed,
    /// Отдельные куски с промежутками воздуха: соцветия, салат, ягоды горкой.
    Loose,
}

impl Packing {
    /// Из ответа модели. Незнакомое слово — `Packed`: это середина шкалы, и ошибка
    /// от неё меньше, чем от любого края.
    pub fn parse(s: &str) -> Self {
        match s.trim().to_lowercase().as_str() {
            "solid" => Self::Solid,
            "loose" => Self::Loose,
            _ => Self::Packed,
        }
    }

    /// Доля занятого объёма и вес кубического сантиметра.
    ///
    /// Числа грубые и взяты из здравого смысла, а не из замера, — поэтому и стоят
    /// здесь, на виду, а не внутри модели. Подтверждены пока только на `Loose`
    /// (соцветия капусты) и `Packed` (тушёное мясо); `Solid` на взвешенной рыбе
    /// давал перебор, но виновата там была толщина, а не эти числа: у рыбы плотность
    /// около 1.05, и заполнение 0.90 для филе близко к правде.
    fn fill_and_density(self) -> (f64, f64) {
        match self {
            Self::Solid => (0.90, 1.00),
            Self::Packed => (0.80, 0.95),
            Self::Loose => (0.45, 0.90),
        }
    }
}

/// Одна еда на посуде — то, что модель называет, не касаясь граммов.
#[derive(Debug, Clone)]
pub struct Region {
    pub name: String,
    /// Какую долю ДНА посуды закрывает эта еда, если смотреть сверху.
    pub share_of_plate: f64,
    /// Насколько высоко еда поднимается над дном, в сантиметрах.
    pub thickness_cm: f64,
    pub packing: Packing,
}

/// Откуда взялся поперечник посуды. Не украшение: от этого зависит, насколько можно
/// доверять весу, и человек имеет право это видеть.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PlateSource {
    /// Задан человеком — свою посуду он один раз обмерил.
    Known,
    /// Измерен по столовому прибору в кадре. На снимке с рыбой дал 19.2 см при 19.
    Measured,
    /// Прикинут моделью: прибора в кадре не было. Ошибка площади около 16%, и
    /// маленькую посуду она завышает, а большую занижает, обе тянет к 22 см.
    Guessed,
}

/// Разумные пределы поперечника посуды. Не «на всякий случай»: ошибка диаметра
/// возводится в квадрат при переходе к площади, поэтому явная нелепость должна
/// отсекаться до того, как превратится в килограмм еды.
const MIN_PLATE_CM: f64 = 8.0;
const MAX_PLATE_CM: f64 = 40.0;

pub fn plate_is_plausible(cm: f64) -> bool {
    cm.is_finite() && (MIN_PLATE_CM..=MAX_PLATE_CM).contains(&cm)
}

/// Площадь дна посуды по поперечнику, см².
pub fn plate_area_cm2(diameter_cm: f64) -> f64 {
    std::f64::consts::PI * (diameter_cm / 2.0).powi(2)
}

/// Вес одной еды: площадь дна на долю, на толщину, на заполнение и плотность.
pub fn grams(diameter_cm: f64, r: &Region) -> f64 {
    let (fill, density) = r.packing.fill_and_density();
    plate_area_cm2(diameter_cm) * r.share_of_plate * r.thickness_cm * fill * density
}

/// Поперечник посуды по рамкам: во сколько раз она шире предмета известного размера.
///
/// Рамки приходят долями кадра, но кадр НЕ КВАДРАТНЫЙ, и одна и та же доля по
/// горизонтали и по вертикали — разное число пикселей. Считать длины прямо в долях
/// значит растянуть кадр в квадрат: на замере это дало 74% ошибки там, где после
/// перевода в пиксели вышло 2%.
///
/// У посуды берём большую сторону рамки: снятая под углом тарелка становится
/// эллипсом, и длинная ось ближе к настоящему поперечнику. У прибора — диагональ:
/// он лежит наискось, и его длина это диагональ, а не сторона.
pub fn plate_cm_from_boxes(
    plate: [f64; 4],
    reference: [f64; 4],
    reference_cm: f64,
    frame_w: f64,
    frame_h: f64,
) -> Option<f64> {
    if frame_w <= 0.0 || frame_h <= 0.0 || reference_cm <= 0.0 {
        return None;
    }
    let plate_px = ((plate[2] - plate[0]).abs() * frame_w).max((plate[3] - plate[1]).abs() * frame_h);
    let ref_px =
        (((reference[2] - reference[0]) * frame_w).powi(2) + ((reference[3] - reference[1]) * frame_h).powi(2)).sqrt();
    if ref_px <= 0.0 || plate_px <= 0.0 {
        return None;
    }
    let cm = plate_px / ref_px * reference_cm;
    plate_is_plausible(cm).then_some(cm)
}

/// Длина столового прибора в сантиметрах. Годятся ТОЛЬКО приборы: они разбросаны по
/// размеру мало, лежат в одной плоскости с посудой и не путаются между собой.
///
/// Числа здесь — ДОПУЩЕНИЕ, и оно само несёт ошибку. На снимке с рыбой вилка заняла
/// 1068 пикселей при тарелке в 1213; с принятыми 19.5 см это даёт поперечник 22.1,
/// тогда как тарелка 19. То есть вилка у того человека около 17.6 см. Столовые вилки
/// бывают от 17.5 до 20.5, и подгонять эту таблицу под одного человека нельзя —
/// зато отсюда видно, что даже верно измеренное отношение оставляет около десятой
/// части ошибки, пока длина прибора взята из справочника, а не измерена.
///
/// Телефон сюда не входит намеренно. Телефоны 14-17 см, планшеты 25-28, а модель их
/// не различает: на снимке с печенью она назвала планшет телефоном, обвела лишь
/// торчащую из-под тарелки часть и завысила посуду на 14%, что превратилось в 40%
/// ошибки веса. Запрет в промпте её не остановил; отсутствие в этой таблице —
/// останавливает, отправляя ответ на запасной путь.
pub fn reference_cm(kind: &str) -> Option<f64> {
    match kind.trim().to_lowercase().as_str() {
        "fork" => Some(19.5),
        "spoon" => Some(19.0),
        "knife" => Some(21.0),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn region(name: &str, share: f64, thick: f64, packing: Packing) -> Region {
        Region { name: name.into(), share_of_plate: share, thickness_cm: thick, packing }
    }

    /// Тарелка с печенью: человек взвесил 300 г печени и 400 г цветной капусты,
    /// посуда большая, 26 см. Доли и толщины — то, что модель называла в замере.
    #[test]
    fn weighed_plate_of_liver_and_cauliflower() {
        let cauliflower = grams(26.0, &region("капуста", 0.6, 3.5, Packing::Loose));
        let meat = grams(26.0, &region("мясо", 0.4, 2.0, Packing::Packed));
        assert!((cauliflower / 400.0 - 1.0).abs() < 0.15, "капуста: {cauliflower:.0} г при 400");
        assert!((meat / 300.0 - 1.0).abs() < 0.15, "мясо: {meat:.0} г при 300");
    }

    /// А это граница применимости, и тест держит её НАМЕРЕННО. Рыба взвешена:
    /// скумбрия 83 г, сельдь 72 г, посуда маленькая, 19 см. С теми долями и
    /// толщинами, что называет модель, выходит вдвое больше — потому что толщины на
    /// снимке сверху нет, и модель её не мерит, а вспоминает.
    ///
    /// Если этот тест однажды упадёт, значит способ научились чинить, и упасть он
    /// должен ГРОМКО: тогда надо переписать и его, и предупреждение в шапке модуля.
    #[test]
    fn flat_food_is_overestimated_and_we_know_it() {
        let mackerel = grams(19.0, &region("скумбрия", 0.3, 1.8, Packing::Solid));
        assert!(mackerel > 83.0 * 1.5, "плоское завышается: {mackerel:.0} г при 83");
    }

    /// Снимок с рыбой, обмеренный по пикселям: тарелка 1213 px, вилка наискось 1068
    /// px, кадр 1536x1152. Отношение — 1.14, и его функция обязана посчитать верно.
    ///
    /// Настоящая тарелка при этом 19 см, а не 22: вилка у того человека около 17.6
    /// см, а не справочные 19.5. Тест проверяет АРИФМЕТИКУ, а не совпадение с
    /// эталоном — подогнать второе можно только подогнав длину чужой вилки.
    #[test]
    fn plate_from_boxes_accounts_for_frame_aspect() {
        let plate = [0.20, 0.01, 0.99, 0.96];
        let fork = [0.075, 0.568, 0.752, 0.781];

        let cm = plate_cm_from_boxes(plate, fork, 19.5, 1536.0, 1152.0).unwrap();
        assert!((cm - 22.1).abs() < 0.3, "отношение 1.14 на 19.5 см даёт 22.1, вышло {cm:.1}");

        // С настоящей длиной вилки та же арифметика даёт настоящий поперечник.
        let with_real_fork = plate_cm_from_boxes(plate, fork, 17.6, 1536.0, 1152.0).unwrap();
        assert!((with_real_fork - 19.0).abs() < 1.0, "{with_real_fork:.1} см при настоящих 19");

        // Тот же счёт БЕЗ перевода в пиксели (кадр как квадрат) — так было, и так
        // ошибка достигала 74%.
        let square = plate_cm_from_boxes(plate, fork, 19.5, 1000.0, 1000.0).unwrap();
        assert!((square - cm).abs() > 3.0, "квадратный кадр обязан давать другой ответ");
    }

    #[test]
    fn absurd_plate_is_rejected() {
        assert!(!plate_is_plausible(3.0));
        assert!(!plate_is_plausible(120.0));
        assert!(!plate_is_plausible(f64::NAN));
        assert!(plate_is_plausible(19.0));
        // Рамка нулевой длины не должна становиться бесконечным поперечником.
        assert_eq!(plate_cm_from_boxes([0.0, 0.0, 1.0, 1.0], [0.5, 0.5, 0.5, 0.5], 19.5, 1536.0, 1152.0), None);
    }

    #[test]
    fn only_cutlery_is_a_usable_reference() {
        assert_eq!(reference_cm("fork"), Some(19.5));
        assert_eq!(reference_cm("SPOON"), Some(19.0));
        // Телефон и планшет модель путает, а разница между ними двукратная.
        assert_eq!(reference_cm("phone"), None);
        assert_eq!(reference_cm("tablet"), None);
        assert_eq!(reference_cm("none"), None);
    }

    #[test]
    fn unknown_packing_falls_to_the_middle() {
        assert_eq!(Packing::parse("solid"), Packing::Solid);
        assert_eq!(Packing::parse("loose"), Packing::Loose);
        assert_eq!(Packing::parse("что-то новое"), Packing::Packed);
    }
}
