//! Спросить кальций заново: у него сменились и промпт, и справочник.
//!
//! Прежние значения набраны запросом, который спрашивал продукт по голому имени из
//! дневника — без опознания, без ключа записи и с таблицей, показанной вместе с
//! числами. Замер тогда давал 26 из 30 по строке и 30 из 30 по величине, но живой
//! проход показал, чего эти цифры стоят: «Голец» получал 120 мг как «жидкий молочный
//! продукт вроде кефира», «Мороженая вишня» — 130 мг по созвучной записи «мороженое
//! сливочное», отварной картофель — ноль, потому что фруктов и овощей в таблице не
//! было вовсе, а «Полба» — 1460 мг, число МАКА, потому что круп там тоже не было.
//!
//! Теперь запрос идёт с готовым опознанием, справочник отвечает ключом записи, а
//! таблица показывается без чисел. Замер: строка 36 из 37, величина 37 из 37.
//!
//! Стираем у ВСЕХ продуктов: какое именно значение испорчено, снаружи не видно — те
//! же 25 мг могут быть и верной рыбой, и случайным попаданием. Фоновый проход
//! переспросит по одному запросу на продукт, разово.
//!
//! Клетчатку не трогаем, хотя справочник появился и у неё: она едет прицепом на
//! растительном узле, а тот спрашивается вместе с признаком «овощ или фрукт» — и
//! сбрасывать признак ради числа значило бы переспросить вдвое больше.

use api_types::Food;

use crate::services::db;
use crate::services::indicators::N_CALCIUM;

pub const VERSION: u32 = 19;
pub const DESCRIPTION: &str = "переспросить кальций: новый промпт и справочник";

pub async fn script() -> Result<(), String> {
    let foods: Vec<Food> = db::list_all("foods").await;
    let mut cleared = 0_usize;
    let mut touched: Vec<String> = Vec::new();
    for mut food in foods {
        // Блюда считаются из состава, а не спрашиваются, — их кальций пересчитается
        // сам, когда переспросятся ингредиенты.
        if food.is_recipe || !food.nutrients.contains_key(N_CALCIUM) {
            continue;
        }
        food.nutrients.remove(N_CALCIUM);
        food.updated_at = crate::services::local::now();
        db::put("foods", &food).await;
        touched.push(food.id.clone());
        cleared += 1;
    }
    leptos::logging::log!("миграция 19: кальций сброшен у продуктов: {cleared}");
    if cleared > 0 {
        // Дни, где эти продукты ели, посчитаны со старым кальцием — пересчитать.
        for id in touched {
            crate::services::indicators::invalidate_food(&id).await;
        }
        crate::services::sync::push_background();
    }
    Ok(())
}
