//! Стереть накопленную «Омегу-3» из карты нутриентов.
//!
//! Значения собирались общим проходом `enrich` как обычный нутриент: одно число в
//! миллиграммах на 100 г, без таблицы категорий, — то самое «назови число», от
//! которого мы отказались ещё на кальции и железе. Отсюда две беды разом.
//!
//! Первая: сами числа недостоверны. Вторая, важнее: «омега-3» одним числом не
//! измеряется. EPA+DHA из рыбы и АЛК из растительного масла — разные вещи, организм
//! делает первое из второго с конверсией в единицы процентов, и недельная норма
//! 3500 мг закрывалась одной порцией скумбрии.
//!
//! Теперь и то, и другое считается из ПРОФИЛЯ жира (`services::fats`): доли кислот от
//! жира продукта × наш собственный жир. Старый ключ больше никем не читается и в
//! интерфейсе скрыт, но в данных он мешает: занимает место, уезжает в синк и
//! всплывает в выгрузках. Стирается.
//!
//! Кальций, клетчатка, железо и теги не трогаются.

use api_types::Food;

use crate::services::{db, indicators, local, sync};

pub const VERSION: u32 = 7;
pub const DESCRIPTION: &str = "стереть омегу-3, собранную общим проходом";

pub async fn script() -> Result<(), String> {
    let mut cleared = 0usize;
    for mut food in local::list_foods().await {
        if food.nutrients.remove(indicators::N_OMEGA3).is_none() {
            continue;
        }
        food.updated_at = local::now();
        db::put::<Food>("foods", &food).await;
        // Дни, в которые продукт ели, держат агрегаты в кэше.
        indicators::invalidate_food(&food.id).await;
        cleared += 1;
    }
    leptos::logging::log!("миграция 7: омега-3 стёрта у продуктов — {cleared}");
    if cleared > 0 {
        sync::push_background();
    }
    Ok(())
}
