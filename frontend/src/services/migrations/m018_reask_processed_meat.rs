//! Спросить мясо глубокой переработки заново: копчёная рыба считалась колбасой.
//!
//! Промпт спрашивал «консервировано ли это МЯСО», перечислял копчение, посол и
//! вяление, а рыбу ограждал единственной оговоркой — «рыба, НЕ прошедшая этих
//! обработок». Копчёная рыба под неё не подпадала и уходила в колбасы: съеденная
//! скумбрия холодного копчения показывалась в дневнике как «86 г колбасы».
//! Слабосолёный лосось падал так же.
//!
//! Оговорка переписана и, главное, ПЕРЕЕХАЛА в перечень случаев «нет». Первая
//! попытка ставила её сразу после вопроса — и делала хуже (29/32 против 30/32):
//! абзац про рыбу читался раньше определения «что значит консервировано» и тянул
//! к «нет» вообще, ломая даже сыровяленую колбасу. С того же места, где стоят
//! прочие «нет», она дала 32/32 (`scripts/measure-meat-flags.mjs`).
//!
//! Признак спрашивается только когда его нет, поэтому стираем его у ВСЕХ
//! продуктов: какой именно ответ испорчен, снаружи не видно. Фоновый проход
//! переспросит — по одному запросу на продукт, разово.
//!
//! Красное мясо не трогаем: замер давал по нему 32/32 и до правки, и после —
//! рыба в ту категорию никогда не попадала.

use api_types::Food;

use crate::services::db;

pub const VERSION: u32 = 18;
pub const DESCRIPTION: &str = "переспросить мясо глубокой переработки: рыба — не колбаса";

pub async fn script() -> Result<(), String> {
    let foods: Vec<Food> = db::list_all("foods").await;
    let mut cleared = 0_usize;
    for mut food in foods {
        if food.is_recipe || food.is_processed_meat.is_none() {
            continue;
        }
        food.is_processed_meat = None;
        food.updated_at = crate::services::local::now();
        db::put("foods", &food).await;
        cleared += 1;
    }
    leptos::logging::log!("миграция 18: переработанное мясо сброшено у продуктов: {cleared}");
    if cleared > 0 {
        crate::services::sync::push_background();
    }
    Ok(())
}
