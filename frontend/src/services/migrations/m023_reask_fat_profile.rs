//! Спросить заново ПРОФИЛЬ ЖИРА.
//!
//! Третий сброс подряд и по той же причине, что овощи-фрукты и гем: профиль жира
//! строился на опознании, которому мы больше не верим. Гейт рубил живые имена, а
//! там, где пропускал, версия продукта нередко была догадкой — и доли насыщенных,
//! мононенасыщенных, полиненасыщенных и ЭПК+ДГК считались уже от неё.
//!
//! Цена ошибки здесь такая же, как у мяса: на профиле держатся три недельных
//! индикатора жиров и шкала баланса, то есть человек видит её прямо на экране.
//!
//! Стираем У ВСЕХ продуктов: какой именно ответ испорчен, снаружи не видно, а
//! половинчатый сброс оставил бы половину вранья. Фоновый проход переспросит по
//! одному запросу на продукт, разово — и теперь уже с опознанием от модели
//! покрупнее.
//!
//! Блюда не трогаются: их профиль считается ИЗ СОСТАВА, и пересчитается сам, как
//! только ингредиент получит новый (`cache_food_fat_profile` → `recompute_recipes_using`).
//! Стереть его здесь значило бы оставить блюда без жиров до конца прохода по всем
//! ингредиентам.
//!
//! Дни пересчитываются: профиль входит в недельные величины, и без сброса кэша
//! шкалы остались бы со старыми числами.

use api_types::Food;

use crate::services::db;

pub const VERSION: u32 = 23;
pub const DESCRIPTION: &str = "переспросить профиль жира после починки опознания";

pub async fn script() -> Result<(), String> {
    let foods: Vec<Food> = db::list_all("foods").await;
    let mut cleared = 0_usize;
    let mut touched: Vec<String> = Vec::new();
    for mut food in foods {
        if food.is_recipe {
            continue;
        }
        if food.fat_profile.is_none() {
            continue;
        }
        food.fat_profile = None;
        food.updated_at = crate::services::local::now();
        db::put("foods", &food).await;
        touched.push(food.id.clone());
        cleared += 1;
    }
    leptos::logging::log!("миграция 23: профиль жира сброшен у продуктов: {cleared}");
    if cleared > 0 {
        for id in touched {
            crate::services::indicators::invalidate_food(&id).await;
        }
        crate::services::sync::push_background();
    }
    Ok(())
}
