//! Пересчитать вердикты дней целиком.
//!
//! Дневной результат каждого индикатора ЗАМОРАЖИВАЕТСЯ: посчитанный день больше не
//! пересчитывается, иначе поднятая планка задним числом переписывала бы прошлое.
//! Обратная сторона — правка самого правила на уже вынесенные вердикты не
//! действует, и каждое изменение формулы требует отдельной миграции, стирающей
//! затронутые дни. Так вышло с правилом «день до первой планки судить нечем»: на
//! него ушли две миграции подряд, тринадцатая и четырнадцатая.
//!
//! Здесь кэш сносится целиком — один раз, чтобы свести накопившиеся правила в одно
//! состояние. Дальше дни считаются заново: последние две недели заморозкой на
//! запуске, остальные — когда их запросит недельное окно.
//!
//! Что при этом ТЕРЯЕТСЯ, и почему сейчас это допустимо:
//!
//! * У начавших раньше самой истории планок промежуточные изменения нигде не
//!   записаны — миграция 3 завела одну запись на вид, датировав её днём создания
//!   цели. Для дней между этими двумя моментами замороженный вердикт был
//!   единственным свидетельством, по чему судили; теперь они пересчитаются по
//!   засеянной планке.
//! * День пересчитывается по НЫНЕШНЕМУ дневнику: правки еды задним числом изменят
//!   старые вердикты, а день, от которого записей не осталось, вердикт потеряет.
//!
//! Обе потери касаются истории, которой у нынешних пользователей почти нет.
//! Повторять этот приём, когда людей станет много, уже нельзя — тогда только
//! точечные миграции, стирающие ровно затронутые дни.

use crate::services::indicators;

pub const VERSION: u32 = 15;
pub const DESCRIPTION: &str = "пересчитать вердикты дней целиком";

pub async fn script() -> Result<(), String> {
    indicators::clear_cache().await;
    leptos::logging::log!("миграция 15: кэш вердиктов снесён, дни пересчитаются заново");
    Ok(())
}
