//! Стереть признак гемового железа у всех продуктов.
//!
//! Первый промпт про гем не был замерен перед выкатом, и на нём вердикт плавал:
//! «Мидии варёно-мороженые, чилийские» получали то `true`, то `false` от прогона
//! к прогону — слова о способе приготовления модель принимала за признак
//! полуфабриката. Плюс в список «моллюсков с высоким содержанием гема» попали
//! кальмар и гребешок, у которых железа меньше миллиграмма на 100 г — не больше,
//! чем у куриной грудки.
//!
//! Переспросить сами по себе такие продукты нечему: [`classify::needs_classification`]
//! идёт только за пустыми полями, а тут поле заполнено — просто неверно. Отличить
//! испорченный ответ от верного задним числом не по чему, поэтому стирается весь
//! признак, и ближайший фоновый проход спрашивает заново — уже по промпту с
//! обоснованием.
//!
//! Остальные теги не трогаются: их промпты не менялись.

use api_types::Food;

use crate::services::{db, indicators, local, sync};

pub const VERSION: u32 = 6;
pub const DESCRIPTION: &str = "стереть признак гема, набранный незамеренным промптом";

pub async fn script() -> Result<(), String> {
    let mut cleared = 0usize;
    for mut food in local::list_foods().await {
        if food.is_heme.is_none() {
            continue;
        }
        food.is_heme = None;
        food.updated_at = local::now();
        db::put::<Food>("foods", &food).await;
        // Дни, в которые продукт ели, держат посчитанные порции в кэше. Сам
        // перезапрос их потом обновит, но если модель недоступна — кэш остался бы
        // считать по стёртому признаку.
        indicators::invalidate_food(&food.id).await;
        cleared += 1;
    }
    leptos::logging::log!("миграция 6: признак гема очищен у продуктов — {cleared}");
    if cleared > 0 {
        sync::push_background();
    }
    Ok(())
}
