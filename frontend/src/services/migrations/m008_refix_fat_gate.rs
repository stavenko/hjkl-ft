//! Закрыть жиры, открывшиеся задним числом, и начать отсчёт заново.
//!
//! Гейт жиров смотрел на последнюю ЗАВЕРШЁННУЮ неделю железа за всю историю. У
//! человека, закрывшего планку по железу на прошлой неделе — то есть у всех, кто её
//! держит, — эта неделя была закрыта ещё до того, как жиры вообще появились. Поэтому
//! в первый же запуск после обновления дверь открывалась мгновенно: индикаторы,
//! шкалы и история шестой недели возникали сами собой, ни за что.
//!
//! Правило должно быть другим: закрыть планку и дождаться конца недели. Оно и
//! введено — недели теперь считаются от якоря [`fats::FAT_GATE_ANCHOR_KEY`]. Но флаг
//! у тех, кто успел обновиться, уже стоит, а сам по себе он не снимается: флаги
//! разблокировки монотонны.
//!
//! Здесь — единственное исключение, и оно узкое. Открытие произошло минуты назад и
//! ЗАРАБОТАНО не было: за это время закрыть неделю невозможно. Снимаем флаг, стираем
//! якорь недели жира и ставим якорь гейта на сегодня — отсчёт начинается с этого дня.
//!
//! Профили жира у продуктов НЕ трогаются: они собраны верно и пригодятся, когда жиры
//! откроются по-настоящему.

use crate::services::{app_flags, fats, local};

pub const VERSION: u32 = 8;
pub const DESCRIPTION: &str = "закрыть жиры, открывшиеся задним числом";

pub async fn script() -> Result<(), String> {
    if !fats::unlocked() {
        // Не открывались — нечего и снимать. Якорь поставит сам гейт при первом
        // запуске, когда железо уже открыто.
        return Ok(());
    }
    app_flags::set_bool(fats::FAT_UNLOCKED_KEY, false);
    app_flags::remove(fats::FAT_WEEK_OPEN_KEY);
    app_flags::set(fats::FAT_GATE_ANCHOR_KEY, &local::today_date().format("%Y-%m-%d").to_string());
    leptos::logging::log!("миграция 8: жиры закрыты, отсчёт гейта начат заново");
    crate::services::sync::push_background();
    Ok(())
}
