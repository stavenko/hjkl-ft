//! Расчистить дни, осуждённые по планке, которой тогда не было.
//!
//! День по калориям судился так: нет планки в истории на эту дату — берём
//! ТЕКУЩУЮ. Из-за этого первая же выдача планки перекрашивала всю неделю
//! наблюдений в перебор: человек ел 3850 ккал, планку получил на 3550 — и задним
//! числом оказывался виноват в том, что ел до неё. Правило поменялось: день до
//! первой установки судить нечем, планкой становится съеденное, и день
//! засчитывается.
//!
//! Но вердикты дней ЗАМОРАЖИВАЮТСЯ (`ind_calories`), и уже вынесенные новым
//! правилом сами не пересчитаются — заморозка на то и заморозка. Стираем ровно
//! те записи, что относятся к дням РАНЬШЕ первой установки калорийной планки:
//! они пересчитаются при ближайшем открытии приложения, уже по-новому.
//!
//! Дни с планкой не трогаем: их вердикт законен, и пересчёт по сегодняшнему
//! значению как раз и был бы переписыванием прошлого.

use crate::services::{db, local};

pub const VERSION: u32 = 13;
pub const DESCRIPTION: &str = "расчистить дни, осуждённые до появления планки";

/// Кэш вердиктов по калориям — тот же стор, что чистит `invalidate_day`.
const STORE: &str = "ind_calories";

#[derive(serde::Deserialize)]
struct Day {
    date: String,
}

pub async fn script() -> Result<(), String> {
    // Первая установка планки в истории. Её нет вовсе — значит планки не было
    // никогда, и осуждать было не по чему ни один день.
    let first = local::planka_history(local::PLANKA_CALORIES)
        .await
        .into_iter()
        .next()
        .map(|e| e.date);

    let days: Vec<Day> = db::list_all(STORE).await;
    let mut cleared = 0_usize;
    for day in days {
        let before_planka = match &first {
            Some(from) => day.date.as_str() < from.as_str(),
            None => true,
        };
        if before_planka {
            db::delete(STORE, &day.date).await;
            cleared += 1;
        }
    }
    leptos::logging::log!(
        "миграция 13: снято вердиктов за дни без планки: {cleared} (планка с {first:?})"
    );
    Ok(())
}
