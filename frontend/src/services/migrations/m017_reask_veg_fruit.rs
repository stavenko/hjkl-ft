//! Спросить овощ/фрукт заново: признак отвечал «нет» почти на всё.
//!
//! Прежний промпт был вопросом «да/нет» с отрицательным перечнем в хвосте, и он не
//! работал: модель писала верную причину и ставила противоположный вердикт —
//! «Яблоко → false, apple is a fruit», «Огурец → false, it is a cucumber». Замер
//! живым путём давал 9 попаданий из 20, причём мимо шли яблоко, банан, огурец,
//! картофель и все ягоды, а не спорные случаи. То есть у людей овощи и фрукты
//! почти поголовно помечены как «не овощ и не фрукт», и всё, что на этом признаке
//! построено, считалось по пустому множеству.
//!
//! Промпт переписан по образцу гема (опознание своим полем, категории заданы
//! положительно, ягоды названы прямо), а вердикт теперь не спрашивается вовсе — он
//! выводится из названной категории, так что противоречить ей больше нечему. Замер
//! после этого: 20/20 три прогона подряд (`scripts/measure-veg-fruit.mjs`).
//!
//! Хранимые ответы этого не знают: признак спрашивается только когда его нет.
//! Поэтому стираем его у ВСЕХ продуктов — какой именно ответ испорчен, снаружи не
//! видно, а половинчатый сброс оставил бы половину вранья. Фоновый проход
//! переспросит: по одному запросу на продукт, разово.
//!
//! Блюда не трогаются: у них признака нет вовсе, овощи и фрукты блюда считаются из
//! состава.

use api_types::Food;

use crate::services::db;

pub const VERSION: u32 = 17;
pub const DESCRIPTION: &str = "переспросить овощ/фрукт после починки промпта";

pub async fn script() -> Result<(), String> {
    let foods: Vec<Food> = db::list_all("foods").await;
    let mut cleared = 0_usize;
    for mut food in foods {
        if food.is_recipe || food.is_veg_fruit.is_none() {
            continue;
        }
        food.is_veg_fruit = None;
        food.updated_at = crate::services::local::now();
        db::put("foods", &food).await;
        cleared += 1;
    }
    leptos::logging::log!("миграция 17: овощ/фрукт сброшен у продуктов: {cleared}");
    if cleared > 0 {
        crate::services::sync::push_background();
    }
    Ok(())
}
