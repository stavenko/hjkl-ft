//! Стереть железо у всех продуктов — второй раз.
//!
//! Первая инвалидация (миграция 1) убрала значения, где миллиграммы повторяли долю
//! усвоения. Набранные после неё оказались испорчены иначе — совмещённый промпт
//! выбирал категорию и величину разом и промахивался категорией:
//!
//!   • арбуз попал в мясную строку — 1.5 мг с усвоением 0.15, и килограмм арбуза дал
//!     2.25 мг усвоенного за один обед;
//!   • безалкогольное пиво попало в «обогащённые железом» — 10 мг с усвоением 0.05,
//!     то есть 0.5 мг усвоенного на 100 мл;
//!   • голец был объявлен говядиной.
//!
//! За день так набегало 9 мг при недельной норме 10.1. Теперь категорию и величину
//! определяют разные шаги конвейера, доля усвоения берётся только из таблицы, а
//! содержание — у модели, когда она уверена. Старые числа этому не соответствуют и
//! отличить их от новых нечем, поэтому стираются все.
//!
//! Кальций НЕ трогается: он пересчитан своей таблицей и с этой бедой не связан.

use api_types::Food;

use crate::services::{db, indicators, local, sync};

pub const VERSION: u32 = 4;
pub const DESCRIPTION: &str = "стереть железо, набранное совмещённым промптом";

pub async fn script() -> Result<(), String> {
    let mut cleared = 0usize;
    for mut food in local::list_foods().await {
        if food.iron_mg.is_none() && food.iron_absorption.is_none() {
            continue;
        }
        food.iron_mg = None;
        food.iron_absorption = None;
        food.updated_at = local::now();
        db::put::<Food>("foods", &food).await;
        // Дни, в которые продукт ели, обязаны пересчитаться — недельная полоса железа
        // выводится из дневника при каждом чтении, но кэш дней держит агрегаты.
        indicators::invalidate_food(&food.id).await;
        cleared += 1;
    }
    leptos::logging::log!("миграция 4: железо очищено у продуктов — {cleared}");
    if cleared > 0 {
        sync::push_background();
    }
    Ok(())
}
