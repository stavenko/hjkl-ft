//! Приведение строк к виду, в котором их сравнивает поиск еды.
//!
//! Поиск ищет подстроку в названии, и до сих пор сравнивал ровно то, что человек
//! набрал: «Яблоко » с пробелом на конце не находило «Яблоко», потому что пробел —
//! такой же символ, как буква. На телефоне это ловушка: iOS ставит пробел сам,
//! автозаменой и двойным тапом по пробелу, — человек видит своё слово и пустой
//! список под ним.
//!
//! Поэтому и запрос, и название прогоняются через одну и ту же нормализацию:
//! регистр вниз, всё, что не буква и не цифра, — в пробел, пробелы схлопываются.
//! Так «Яблоко », «яблоко.» и «Яблоко (Голден)» ищут одно и то же, а «сыр
//! творожный» находит «Сыр, творожный».
//!
//! Ё И Е ОСТАВЛЕНЫ РАЗНЫМИ: это разные буквы, и подмена одной на другую — уже не
//! очистка от мусора, а догадка о том, что человек имел в виду.

/// Строка в том виде, в котором её сравнивает поиск.
pub fn normalize(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut space = false;
    for ch in s.chars() {
        if ch.is_alphanumeric() {
            if space && !out.is_empty() {
                out.push(' ');
            }
            space = false;
            out.extend(ch.to_lowercase());
        } else {
            space = true;
        }
    }
    out
}

/// Находится ли `name` по запросу `query`. Пустой запрос находит всё.
pub fn matches(name: &str, query: &str) -> bool {
    let q = normalize(query);
    q.is_empty() || normalize(name).contains(&q)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn probel_po_krayam_ne_meshaet() {
        assert!(matches("Яблоко", "Яблоко "));
        assert!(matches("Яблоко", " яблоко"));
        assert!(matches("Яблоко", "  "), "запрос из одних пробелов — как пустой");
    }

    #[test]
    fn punktuaciya_ne_meshaet() {
        assert!(matches("Сыр, творожный", "сыр творожный"));
        assert!(matches("Яблоко (Голден)", "яблоко голден"));
        assert!(matches("Яблоко", "яблоко."));
    }

    #[test]
    fn poisk_vsyo_eshchyo_ishchet_podstroku() {
        assert!(matches("Зелёное яблоко", "яблок"));
        assert!(!matches("Яблоко", "груша"));
        assert!(!matches("Зелёное яблоко", "яблоко зелёное"), "порядок слов важен");
    }

    #[test]
    fn yo_i_e_raznye_bukvy() {
        assert!(!matches("Зелёное яблоко", "зеленое"));
    }
}
