//! Флаги новых возможностей — включаются КУРАТОРОМ, а не человеком.
//!
//! Новый способ записи еды выкатывается не всем сразу: сперва его включают
//! отдельным людям и смотрят, что вышло. Ручки в настройках для этого нет и не
//! должно быть — человек не обязан знать, что у него внутри две записи еды.
//! Включение приходит директивой из кураторского чата, тем же путём, что и правка
//! планки: сообщение с видом `set_feature` и нагрузкой `{feature, on}`.
//!
//! Хранится флаг в `app_flags` и потому ЕЗДИТ МЕЖДУ УСТРОЙСТВАМИ человека: куратор
//! включил возможность один раз, и она есть и в телефоне, и в браузере. Это
//! отличает флаг от того, что лежит в `DEVICE_LOCAL_KEYS`, — там вещи, которые у
//! каждого устройства свои.
//!
//! Список известных возможностей закрыт. Имя, которого здесь нет, директива не
//! включает: иначе опечатка куратора завела бы флаг, который никто никогда не
//! прочитает, а человек остался бы со старым видом, не понимая почему.

use crate::services::app_flags;

/// Новый способ записи еды: снимки и описание вместо трёх вкладок, распознавание
/// в фоне, ленивая запись в дневнике. Включает ТОЛЬКО добавление новой еды —
/// поиск, дневник и всё, что уже записано, работают как работали.
pub const LAZY_FOOD: &str = "lazy_food";

/// Возможности, которые директива вправе включать.
const KNOWN: &[&str] = &[LAZY_FOOD];

pub fn is_known(feature: &str) -> bool {
    KNOWN.contains(&feature)
}

/// Ключ в `app_flags`. С приставкой, чтобы флаги возможностей нельзя было спутать
/// с прочими ключами приложения и чтобы их было видно скопом.
fn key(feature: &str) -> String {
    format!("feature.{feature}")
}

/// Включена ли возможность. Неизвестное имя — всегда «нет»: читать флаг, которого
/// нет в списке, значит читать опечатку.
pub fn is_on(feature: &str) -> bool {
    is_known(feature) && app_flags::get_bool(&key(feature))
}

/// Включить или выключить. Зовётся из обработчика директивы, не из интерфейса.
pub fn set(feature: &str, on: bool) {
    if is_known(feature) {
        app_flags::set_bool(&key(feature), on);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_features_are_closed_list() {
        assert!(is_known(LAZY_FOOD));
        assert!(!is_known("lazy_foods"));   // опечатка куратора
        assert!(!is_known(""));
    }

    #[test]
    fn key_is_prefixed() {
        assert_eq!(key(LAZY_FOOD), "feature.lazy_food");
    }
}
