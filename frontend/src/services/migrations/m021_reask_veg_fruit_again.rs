//! Спросить овощ/фрукт заново — второй раз, и по другой причине, чем в
//! [`super::m017_reask_veg_fruit`].
//!
//! Тогда чинился сам промпт признака. Теперь сменилось ОПОЗНАНИЕ, которое стоит
//! перед ним: гейт рубил живые продукты, у которых в имени было слово, незнакомое
//! модели, — марка, опечатка, редкая форма. Признание спрашивалось про слово, а не
//! про еду, и модель отвечала буквально честно; вес уходил под порог.
//!
//! Признак от этого страдал двумя способами. Продукт, не прошедший гейт, оставался
//! без признака вовсе — а «нет признака» и «не овощ» на дашборде выглядят
//! одинаково: овощная планка просто недосчитывалась. А там, где опознание всё же
//! проходило, оно приходило в узел растения строкой, построенной на догадке, и
//! признак считался уже по ней.
//!
//! Стираем у ВСЕХ продуктов: какой именно ответ испорчен, снаружи не видно.
//! Фоновый проход переспросит по одному запросу на продукт, разово.
//!
//! Блюда не трогаются: у них признака нет вовсе, овощи и фрукты блюда считаются из
//! состава.
//!
//! В отличие от семнадцатой, здесь ещё и пересчитываются дни: признак входит в
//! дневные индикаторы, и без сброса кэша экран остался бы с прежними цветами.

use api_types::Food;

use crate::services::db;

pub const VERSION: u32 = 21;
pub const DESCRIPTION: &str = "переспросить овощ/фрукт после починки опознания";

pub async fn script() -> Result<(), String> {
    let foods: Vec<Food> = db::list_all("foods").await;
    let mut cleared = 0_usize;
    let mut touched: Vec<String> = Vec::new();
    for mut food in foods {
        if food.is_recipe || food.is_veg_fruit.is_none() {
            continue;
        }
        food.is_veg_fruit = None;
        food.updated_at = crate::services::local::now();
        db::put("foods", &food).await;
        touched.push(food.id.clone());
        cleared += 1;
    }
    leptos::logging::log!("миграция 21: овощ/фрукт сброшен у продуктов: {cleared}");
    if cleared > 0 {
        for id in touched {
            crate::services::indicators::invalidate_food(&id).await;
        }
        crate::services::sync::push_background();
    }
    Ok(())
}
