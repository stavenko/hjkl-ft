//! Спросить гем заново: прежний промпт врал на субпродуктах птицы.
//!
//! Печень стояла в списке «да», птица — в списке «нет», и куриная печень попадала
//! под оба правила разом; побеждало исключение, и печень цыплят-бройлеров
//! объявлялась не источником гемового железа. Определение переписано процедурой с
//! остановкой на первом шаге, а порядок полей в ответе — обоснование раньше
//! вердикта — вылечил свинину и куриные сердечки. Замер: было 19/22, стало 22/22
//! (`scripts/measure-heme.mjs`).
//!
//! Хранимые ответы этого не знают: признак спрашивается только когда его нет.
//! Поэтому стираем его у ВСЕХ продуктов — какой именно ответ испорчен, снаружи не
//! видно, а половинчатый сброс оставил бы половину вранья. Фоновый проход
//! переспросит: по одному запросу на продукт, разово.
//!
//! Блюда не трогаются: у них признака нет вовсе, гем блюда считается из состава.

use api_types::Food;

use crate::services::db;

pub const VERSION: u32 = 12;
pub const DESCRIPTION: &str = "переспросить гем после починки промпта";

pub async fn script() -> Result<(), String> {
    let foods: Vec<Food> = db::list_all("foods").await;
    let mut cleared = 0_usize;
    for mut food in foods {
        if food.is_recipe || food.is_heme.is_none() {
            continue;
        }
        food.is_heme = None;
        food.updated_at = crate::services::local::now();
        db::put("foods", &food).await;
        cleared += 1;
    }
    leptos::logging::log!("миграция 12: гем сброшен у продуктов: {cleared}");
    if cleared > 0 {
        crate::services::sync::push_background();
    }
    Ok(())
}
