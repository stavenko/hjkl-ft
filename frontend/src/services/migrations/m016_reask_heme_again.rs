//! Спросить гем заново: определение изменилось по существу, а не только на словах.
//!
//! Три поправки разом, и каждая переставляет продукты между «да» и «нет»:
//!
//! - категория красного мяса переименована в мясо МЛЕКОПИТАЮЩИХ. «Бедро куриное
//!   печёное» уходило в неё единогласно — в быту тёмное мясо птицы зовут красным, —
//!   и хранимое «да» у куриных бёдер осталось от этого;
//! - колбаса, сосиски и ветчина названы в категории прямо: гем в них ЕСТЬ, и мы
//!   говорим это честно. Хранимое «нет» у колбас теперь неверно;
//! - опознание вынесено в своё поле, и добавлена рамка «имя взято из дневника
//!   питания». Редкие промысловые названия рыб перестали читаться как органы:
//!   «Голец» объявлялся печенью рыбы и получал «да» (набор рыб 1/10 → 10/10).
//!
//! Хранимые ответы этого не знают: признак спрашивается только когда его нет.
//! Поэтому стираем его у ВСЕХ продуктов — какой именно ответ испорчен, снаружи не
//! видно, а половинчатый сброс оставил бы половину вранья. Фоновый проход
//! переспросит: теперь по ОДНОМУ запросу на продукт, без голосования (замер
//! `scripts/measure-heme-repeat.mjs`: 22/22 пять прогонов подряд, ноль ошибок на
//! каждой позиции).
//!
//! Блюда не трогаются: у них признака нет вовсе, гем блюда считается из состава.
//! Это дословно повторяет [`super::m012_reask_heme`] — тот же сброс по той же
//! причине, но по другому поводу; общего кода у миграций намеренно нет, каждая
//! остаётся снимком своего момента.

use api_types::Food;

use crate::services::db;

pub const VERSION: u32 = 16;
pub const DESCRIPTION: &str = "переспросить гем: мясо млекопитающих, колбаса, опознание";

pub async fn script() -> Result<(), String> {
    let foods: Vec<Food> = db::list_all("foods").await;
    let mut cleared = 0_usize;
    for mut food in foods {
        if food.is_recipe || food.is_heme.is_none() {
            continue;
        }
        food.is_heme = None;
        food.updated_at = crate::services::local::now();
        db::put("foods", &food).await;
        cleared += 1;
    }
    leptos::logging::log!("миграция 16: гем сброшен у продуктов: {cleared}");
    if cleared > 0 {
        crate::services::sync::push_background();
    }
    Ok(())
}
