//! Вернуть отметку «просмотрено» седьмой главе: у неё сменился только фон.
//!
//! Просмотр записывается ХЕШЕМ кадра, а в хеш входит обозначение фона. Когда у
//! недели красного мяса убрали её собственный бордовый фон и перевели кадры на
//! общий, хеши всех её кадров изменились — и глава у всех, кто её уже прочитал,
//! снова загорелась кольцом и уехала в начало ленты. Содержание при этом не
//! менялось ни на букву.
//!
//! Здесь отметки переносятся: для каждого кадра главы считается хеш со СТАРЫМ
//! обозначением фона («meat»), и если он записан как просмотренный, просмотренным
//! отмечается и нынешний хеш. Старые записи не трогаются — они безобидны и стоят
//! шестнадцать байт.
//!
//! Разовое лечение конкретной правки, а не общий механизм: если фон когда-нибудь
//! сменится ещё у одной главы, понадобится своя миграция — или хеш, не зависящий
//! от оформления, но такой переход сам по себе сбросит все отметки разом.

use crate::services::stories;

pub const VERSION: u32 = 22;
pub const DESCRIPTION: &str = "перенести отметки просмотра седьмой главы на новый фон";

pub async fn script() -> Result<(), String> {
    let Some(story) = stories::by_id("week7") else {
        // Главы нет — переносить нечего. Это не поломка: миграция переживёт её
        // возможное переименование.
        return Ok(());
    };
    let mut moved = 0_usize;
    for frame in story.frames {
        let old = frame.hash_with_bg("meat");
        if stories::seen(&old) {
            stories::mark_viewed(&frame.hash());
            moved += 1;
        }
    }
    leptos::logging::log!("миграция 22: перенесено отметок просмотра: {moved}");
    Ok(())
}
