//! Спросить кальций заново — второй раз, и по другой причине, чем в
//! [`super::m019_reask_calcium`].
//!
//! Тогда менялись промпт и справочник. Теперь сменилось ОПОЗНАНИЕ: гейт рубил
//! живые продукты, у которых в имени стояло слово, незнакомое модели, — марка
//! («Calve Майонез», «Экомилк Творожный сыр»), опечатка («ВкусВилл Помбир
//! Сэндвич»), редкая форма («Спиральчатый спагетти»). Признание спрашивалось про
//! слово, и модель отвечала буквально честно; штраф уводил вес под порог, и
//! продукт оставался вообще без разбора.
//!
//! Часть таких продуктов при этом успела получить кальций — до того как гейт
//! появился, или в прогоне, где модель не призналась. Такие значения набраны на
//! опознании, которому мы больше не верим: «Даня творожок» получал 16 мг вместо
//! ста десяти.
//!
//! Сюда же — правки справочника: халва разделилась на подсолнечную (211) и
//! тахинную (420), козинак получил свои 45 вместо халвиных 420, появились
//! «творожок детский» 110, «капуста квашеная» 48, «семена подсолнечника» 78.
//!
//! Стираем у ВСЕХ продуктов по той же причине, что и в прошлый раз: какое именно
//! значение испорчено, снаружи не видно. Фоновый проход переспросит по одному
//! запросу на продукт, разово.

use api_types::Food;

use crate::services::db;
use crate::services::indicators::N_CALCIUM;

pub const VERSION: u32 = 20;
pub const DESCRIPTION: &str = "переспросить кальций: опознание больше не рубит живые имена";

pub async fn script() -> Result<(), String> {
    let foods: Vec<Food> = db::list_all("foods").await;
    let mut cleared = 0_usize;
    let mut touched: Vec<String> = Vec::new();
    for mut food in foods {
        // Блюда считаются из состава, а не спрашиваются, — их кальций пересчитается
        // сам, когда переспросятся ингредиенты.
        if food.is_recipe || !food.nutrients.contains_key(N_CALCIUM) {
            continue;
        }
        food.nutrients.remove(N_CALCIUM);
        food.updated_at = crate::services::local::now();
        db::put("foods", &food).await;
        touched.push(food.id.clone());
        cleared += 1;
    }
    leptos::logging::log!("миграция 20: кальций сброшен у продуктов: {cleared}");
    if cleared > 0 {
        // Дни, где эти продукты ели, посчитаны со старым кальцием — пересчитать.
        for id in touched {
            crate::services::indicators::invalidate_food(&id).await;
        }
        crate::services::sync::push_background();
    }
    Ok(())
}
