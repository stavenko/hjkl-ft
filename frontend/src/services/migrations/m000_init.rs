//! Нулевая миграция: завести поле, в котором живёт версия базы.
//!
//! Единственная, которая обязана работать, когда базы нет вообще — ни данных, ни
//! самого поля версии. Поэтому она ничего не читает и не переписывает, а лишь
//! убеждается, что хранилище флагов доступно на запись и на чтение. Само поле
//! версии заводит раннер сразу после успешного возврата.

use crate::services::app_flags;

pub const VERSION: u32 = 0;
pub const DESCRIPTION: &str = "завести поле версии базы";

/// Пробный ключ. Пишется и тут же удаляется — остаётся только запись версии,
/// которую поставит раннер.
const PROBE_KEY: &str = "db_schema_probe_migrated";

pub async fn script() -> Result<(), String> {
    // Хранилище флагов — то же место, где будет жить версия. Если оно не отвечает,
    // писать версию некуда, и остальные миграции пойдут по кругу: их отметка о
    // выполнении нигде не сохранится. Лучше остановиться здесь.
    // `set` кладёт в кэш сразу, а в базу — фоновой задачей, и проверка попала бы в
    // кэш сама против себя. `set_awaited` дожидается записи, `read_from_db` читает
    // мимо кэша.
    app_flags::set_awaited(PROBE_KEY, "1").await;
    let seen = app_flags::read_from_db(PROBE_KEY).await;
    app_flags::remove(PROBE_KEY);
    match seen.as_deref() {
        Some("1") => Ok(()),
        other => Err(format!(
            "хранилище флагов не отдаёт записанное: ожидали «1», получили {other:?}"
        )),
    }
}
