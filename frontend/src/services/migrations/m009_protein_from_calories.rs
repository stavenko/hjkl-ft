//! Записать планку по белку по НОВОМУ правилу — доле калорийной планки.
//!
//! Раньше норма белка была 1,6 г на кг безжировой массы и записывалась в историю
//! только при взвешивании. Теперь она считается как 30 % калорийной планки, зажатые
//! между 1,6 г/кг безжировой массы снизу и 2,2 г/кг полного веса сверху, и
//! пересчитывается вместе с калорийной планкой ([`local::set_calorie_goal`]).
//!
//! Без этой миграции у обновившегося человека разъехались бы две величины: виджет
//! показывал бы уже НОВУЮ норму (она считается на лету), а день судился бы по
//! СТАРОЙ записи в истории планок — до ближайшего взвешивания или пересчёта
//! калорий, то есть до недели. Пишем новое значение сегодняшним днём.
//!
//! Прошлые дни не трогаются: они уже осуждены по планке, действовавшей тогда, и
//! пересуживать их задним числом нельзя.

use crate::services::local;

pub const VERSION: u32 = 9;
pub const DESCRIPTION: &str = "планка по белку — доля калорийной планки";

pub async fn script() -> Result<(), String> {
    local::record_protein_planka().await;
    crate::services::sync::push_background();
    Ok(())
}
